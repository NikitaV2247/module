# -*- coding: utf-8 -*-
"""Краткие имена дисциплин для отображения.

Полные наименования дисциплин учебного плана длинные (например,
«МДК 02.02 Инструментальные средства разработки программного
обеспечения» — 72 символа). В карточках, таблицах и экспортах
модуль показывает краткую форму из словаря SHORT_NAMES; в CSV
и данных расписание хранит полное наименование.
"""

from __future__ import annotations

SHORT_NAMES: dict[str, str] = {
    "Менеджмент в профессиональной деятельности": "Менеджмент",
    "МДК 01.02 Поддержка и тестирование программных модулей": "МДК 01.02",
    "МДК 01.03 Разработка мобильных приложений": "МДК 01.03",
    "МДК 02.02 Инструментальные средства разработки программного обеспечения": (
        "МДК 02.02"
    ),
    "МДК 11.01 Технологии разработки и защиты баз данных": "МДК 11.01",
}


def display_name(subject: str) -> str:
    """Краткое имя дисциплины для показа человеку.

    Известные длинные наименования сокращаются по словарю
    («МДК 02.02 Инструментальные средства ...» → «МДК 02.02»),
    остальные возвращаются без изменений.
    """
    subject = subject.strip()
    return SHORT_NAMES.get(subject, subject)
